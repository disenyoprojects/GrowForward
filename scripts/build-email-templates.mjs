/**
 * Turns the HTML files in `emails/` into TypeScript modules.
 *
 * The templates in `emails/` stay the single source of truth — designers edit
 * those. This script compiles them into `lib/email/templates/` so the app can
 * import them as plain strings: reading files from disk at runtime is not
 * reliable on Vercel, where only bundled modules are guaranteed to ship.
 *
 * Run with `npm run build:emails` after editing any template.
 */

import { readdir, readFile, writeFile, mkdir, rm } from 'node:fs/promises'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const projectRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const sourceDir = join(projectRoot, 'emails')
const outputDir = join(projectRoot, 'lib', 'email', 'templates')

/** `assets/components.html` is a reference page, not a sendable email. */
const EXCLUDED = new Set(['master-template.html'])

function toCamelCase(fileName) {
  return fileName
    .replace(/\.html$/, '')
    .split('-')
    .map((part, index) =>
      index === 0 ? part : part.charAt(0).toUpperCase() + part.slice(1),
    )
    .join('')
}

function extractSubject(html, fallback) {
  const match = html.match(/<title>([\s\S]*?)<\/title>/i)
  return match ? match[1].trim() : fallback
}

async function main() {
  const entries = await readdir(sourceDir)
  const templates = entries
    .filter((name) => name.endsWith('.html') && !EXCLUDED.has(name))
    .sort()

  if (templates.length === 0) {
    throw new Error(`No email templates found in ${sourceDir}`)
  }

  await rm(outputDir, { recursive: true, force: true })
  await mkdir(outputDir, { recursive: true })

  const index = []

  for (const fileName of templates) {
    const slug = fileName.replace(/\.html$/, '')
    const html = await readFile(join(sourceDir, fileName), 'utf8')
    const subject = extractSubject(html, 'A message from GrowForward')
    const moduleName = toCamelCase(fileName)

    const contents = [
      '/* Generated from emails/' + fileName + ' by scripts/build-email-templates.mjs. */',
      '/* Edit the source template, not this file. */',
      '',
      `export const subject = ${JSON.stringify(subject)}`,
      '',
      `export const html = ${JSON.stringify(html)}`,
      '',
    ].join('\n')

    await writeFile(join(outputDir, `${slug}.ts`), contents, 'utf8')
    index.push({ slug, moduleName })
  }

  const indexContents = [
    '/* Generated by scripts/build-email-templates.mjs. Do not edit. */',
    '',
    ...index.map(
      ({ slug, moduleName }) =>
        `import * as ${moduleName} from './${slug}'`,
    ),
    '',
    'export interface EmailTemplate {',
    '  readonly subject: string',
    '  readonly html: string',
    '}',
    '',
    'export const templates = {',
    ...index.map(({ slug, moduleName }) => `  ${JSON.stringify(slug)}: ${moduleName},`),
    '} as const satisfies Record<string, EmailTemplate>',
    '',
    'export type TemplateName = keyof typeof templates',
    '',
  ].join('\n')

  await writeFile(join(outputDir, 'index.ts'), indexContents, 'utf8')

  console.info(`Compiled ${index.length} email templates to lib/email/templates`)
}

main().catch((error) => {
  console.error('Failed to build email templates:', error)
  process.exitCode = 1
})
